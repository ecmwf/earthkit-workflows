"""Tooling for isolating a suspicious Task, so that it can be re-executed outside of cascade.

Recording (invoked by the worker right before the user callable): `dump_isolation` creates a fresh
directory containing `prepare.sh` (envvars, venv, pip install) and `runtime.py` (func, args, kwargs).
Replay: run `prepare.sh`, then `.venv/bin/python -m cascade.deployment.isolator [path/to/runtime.py]`.
"""

import logging
import os
import platform
import runpy
import shlex
import subprocess
import sys
import tempfile
from base64 import b64encode
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path
from typing import Any

import cloudpickle

logger = logging.getLogger(__name__)

OUTPUT_ENVVAR = "CASCADE_ISOLATOR_OUTPUT"
DEFAULT_PREFIX = "cascade_isolator_"
PREPARE_FILE = "prepare.sh"
RUNTIME_FILE = "runtime.py"
VENV_DIR = ".venv"


def _enc(value: Any) -> str:
    return b64encode(cloudpickle.dumps(value)).decode("ascii")


def _pip_freeze() -> str:
    freezer = ["uv", "pip", "freeze", "--python", sys.executable]
    res = subprocess.run(freezer, capture_output=True, text=True, check=True)
    return res.stdout


def make_output_dir() -> Path:
    """Creates a new directory, not cleaned up automatically. Prefix from CASCADE_ISOLATOR_OUTPUT"""
    prefix = os.environ.get(OUTPUT_ENVVAR, DEFAULT_PREFIX)
    return Path(tempfile.mkdtemp(prefix=prefix))


def dump_environment(target: Path) -> Path:
    """Writes `prepare.sh` into target: exports envvars, creates venv, installs frozen packages"""
    version = platform.python_version()
    freeze = _pip_freeze()
    exports = "\n".join(f"export {k}={shlex.quote(v)}" for k, v in sorted(os.environ.items()) if k.isidentifier())
    # NOTE the heredoc is quoted, so the content is taken literally
    content = f"""#!/usr/bin/env bash
# Generated by cascade.deployment.isolator -- feel free to edit.
# Creates {VENV_DIR} with python {version} and installs the packages below, then exports the original envvars.
# Use via `source prepare.sh`, in order to have the envvars exported in your shell.
# Then run: {VENV_DIR}/bin/python -m cascade.deployment.isolator {RUNTIME_FILE}

_prepare_dir="$(cd "$(dirname "${{BASH_SOURCE[0]:-$0}}")" && pwd)"
cd "$_prepare_dir" || return 1 2>/dev/null || exit 1

PYTHON_VERSION={shlex.quote(version)}

# ---- environment variables ----
{exports}

# ---- venv ----
uv venv --python "$PYTHON_VERSION" {VENV_DIR}
INSTALL=(uv pip install --python {VENV_DIR}/bin/python)

# ---- pip requirements (pip freeze output) ----
cat > requirements.txt <<'CASCADE_ISOLATOR_REQUIREMENTS_EOF'
{freeze.rstrip()}
CASCADE_ISOLATOR_REQUIREMENTS_EOF
"${{INSTALL[@]}}" -r requirements.txt
"""
    path = target / PREPARE_FILE
    path.write_text(content)
    path.chmod(0o755)
    return path


def dump_func(func: Callable | str, args: Sequence[Any], kwargs: Mapping[str, Any], target: Path) -> Path:
    """Writes `runtime.py` into target. If func is a str, it is an entrypoint (eg `mod.func`), otherwise
    a callable which gets cloudpickled. Each arg/kwarg is a separate cloudpickled base64 value"""
    if isinstance(func, str):
        func_line = f"FUNC = resolve_entrypoint({func!r})"
    else:
        func_line = f"FUNC = load({_enc(func)!r})  # {getattr(func, '__qualname__', repr(type(func)))}"
    args_lines = "".join(f"    load({_enc(a)!r}),  # {i}\n" for i, a in enumerate(args))
    kwargs_lines = "".join(f"    {k!r}: load({_enc(v)!r}),\n" for k, v in kwargs.items())
    content = f"""# Generated by cascade.deployment.isolator -- feel free to edit the values below.
# Run via: python -m cascade.deployment.isolator {RUNTIME_FILE}
import importlib
from base64 import b64decode
from typing import Any, Callable

import cloudpickle


def load(value: str) -> Any:
    return cloudpickle.loads(b64decode(value))


def resolve_entrypoint(s: str) -> Callable:
    if "." not in s:
        return eval(s)
    module_name, function_name = s.rsplit(".", 1)
    return importlib.import_module(module_name).__dict__[function_name]


{func_line}

ARGS: list[Any] = [
{args_lines}]

KWARGS: dict[str, Any] = {{
{kwargs_lines}}}
"""
    path = target / RUNTIME_FILE
    path.write_text(content)
    return path


def dump_isolation(func: Callable | str, args: Sequence[Any], kwargs: Mapping[str, Any]) -> Path:
    """Records everything needed to re-execute the call in isolation. Returns the output directory"""
    target = make_output_dir()
    dump_environment(target)
    dump_func(func, args, kwargs, target)
    logger.warning(f"isolation record written to {target} (run {target / PREPARE_FILE}, then python -m cascade.deployment.isolator)")
    return target


def main() -> None:
    path = sys.argv[1] if len(sys.argv) > 1 else RUNTIME_FILE
    ns = runpy.run_path(path)
    func: Callable = ns["FUNC"]
    result = func(*ns["ARGS"], **ns["KWARGS"])
    logger.info(f"isolated execution finished, result type {type(result)}")


if __name__ == "__main__":
    logging.basicConfig(level=logging.DEBUG)
    main()
